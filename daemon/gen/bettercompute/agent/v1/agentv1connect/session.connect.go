//   2. The first ServerFrame is Welcome{epoch}. Then, if applied_generation < generation, a full
//      DesiredState, then a replay of the node's non-terminal commands in seq order.
//   3. The daemon replays unacked results (Hello.unacked_results) and events above
//      Welcome.acked_event_seq; the control plane deduplicates and Acks.
//
// Epoch fencing: routing and liveness writes (dispatch marks, last_seen, disconnect) carry
// `AND session_epoch = $myEpoch`, so a zombie gateway's writes fail. Results, events and status are
