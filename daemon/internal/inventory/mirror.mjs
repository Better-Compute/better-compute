// Generates types.go and encode.go in this directory from proto/bettercompute/agent/v1/inventory.proto:
// Go structs named as protoc-gen-go names them, and a proto3 binary encoder for every section message.
//
//   node daemon/internal/inventory/mirror.mjs
//
// A P0 stopgap: no Go toolchain, so no protoc-gen-go. TODO(v0.1): delete this script, types.go and
// encode.go once daemon/gen holds the generated agent/v1 package; hash_test.go's golden bytes must
// then come out of proto.Marshal unchanged.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const protoPath = join(here, '../../../proto/bettercompute/agent/v1/inventory.proto');
const source = readFileSync(protoPath, 'utf8');

// ---- parse (the subset inventory.proto uses) ---------------------------------------------------

const messages = [];
const enums = [];
let current;
let comments = [];
for (const raw of source.split(/\r?\n/)) {
  const line = raw.trim();
  let m;
  if (line.startsWith('//')) {
    const text = line.replace(/^\/\/ ?/, '');
    if (/^-{10,}$/.test(text)) comments = [];
    else comments.push(text);
  } else if (line === '') {
    if (!current) comments = [];
  } else if ((m = /^message (\w+) \{$/.exec(line))) {
    current = { kind: 'message', name: m[1], doc: comments, fields: [] };
    messages.push(current);
    comments = [];
  } else if ((m = /^enum (\w+) \{$/.exec(line))) {
    current = { kind: 'enum', name: m[1], doc: comments, values: [] };
    enums.push(current);
    comments = [];
  } else if (line === '}') {
    current = undefined;
    comments = [];
  } else if (current?.kind === 'message') {
    m = /^(repeated |optional )?(map<\w+, \w+>|[\w.]+) (\w+) = (\d+);$/.exec(line);
    if (!m) throw new Error(`unparsed field line: ${line}`);
    const [, label = '', type, name, number] = m;
    current.fields.push({ label: label.trim(), type, name, number: Number(number), doc: comments });
    comments = [];
  } else if (current?.kind === 'enum') {
    m = /^(\w+) = (\d+);$/.exec(line);
    if (!m) throw new Error(`unparsed enum line: ${line}`);
    current.values.push({ name: m[1], number: Number(m[2]), doc: comments });
    comments = [];
  } else if (!/^(syntax|package|import|option) /.test(line)) {
    throw new Error(`unparsed line: ${line}`);
  }
}

const enumNames = new Set(enums.map((e) => e.name));
const messageNames = new Set(messages.map((m) => m.name));

// protoc-gen-go's GoCamelCase for the names inventory.proto uses (lowercase words, no digits).
const camel = (name) => name.replace(/(^|_)([a-z])/g, (_, __, c) => c.toUpperCase());

function goType(f) {
  const scalar = { string: 'string', bool: 'bool', uint32: 'uint32', uint64: 'uint64', bytes: '[]byte' };
  if (f.type === 'google.protobuf.Timestamp') return 'time.Time';
  if (f.type === 'map<string, bytes>') return 'map[string][]byte';
  let t = scalar[f.type];
  if (!t && enumNames.has(f.type)) t = f.type;
  if (!t && messageNames.has(f.type)) t = `*${f.type}`;
  if (!t) throw new Error(`unsupported type ${f.type}`);
  if (f.label === 'repeated') return `[]${t}`;
  if (f.label === 'optional') return `*${t}`;
  return t;
}

function encodeLine(f) {
  const field = `m.${camel(f.name)}`;
  const n = f.number;
  if (messageNames.has(f.type)) {
    if (f.label === 'repeated') return [`for _, v := range ${field} {`, `\tw.message(${n}, v.encode)`, '}'];
    return [`if ${field} != nil {`, `\tw.message(${n}, ${field}.encode)`, '}'];
  }
  if (enumNames.has(f.type)) return [`w.enum(${n}, int32(${field}))`];
  if (f.label === 'repeated') {
    if (f.type === 'string') return [`w.strs(${n}, ${field})`];
    throw new Error(`unsupported repeated ${f.type}`);
  }
  const method = { string: 'str', bool: 'boolean', uint32: 'u32', uint64: 'u64' }[f.type];
  if (!method) throw new Error(`unsupported scalar ${f.type} in a section`);
  if (f.label === 'optional') {
    const optional = { bool: 'optBool', uint32: 'optU32', uint64: 'optU64' }[f.type];
    if (!optional) throw new Error(`unsupported optional ${f.type}`);
    return [`w.${optional}(${n}, ${field})`];
  }
  return [`w.${method}(${n}, ${field})`];
}

// ---- emit ---------------------------------------------------------------------------------------

const header = `// Code generated by mirror.mjs from proto/bettercompute/agent/v1/inventory.proto. DO NOT EDIT.\n\n`;
const docLines = (lines, indent = '') => lines.map((l) => (l ? `${indent}// ${l}\n` : `${indent}//\n`)).join('');

// Emits rows as gofmt aligns them: a comment line starts a new alignment block.
function aligned(rows, indent, render) {
  let out = '';
  let block = [];
  const flush = () => {
    const widths = [];
    for (const row of block) row.cells.forEach((c, i) => (widths[i] = Math.max(widths[i] ?? 0, c.length)));
    for (const row of block) {
      const cells = row.cells.map((c, i) => (i < row.cells.length - 1 ? c.padEnd(widths[i] + 1) : c));
      out += `${indent}${cells.join('')}\n`;
    }
    block = [];
  };
  for (const row of rows) {
    if (row.doc.length) {
      flush();
      out += docLines(row.doc, indent);
    }
    block.push({ cells: render(row) });
  }
  flush();
  return out;
}

let types = `${header}package inventory\n\nimport "time"\n`;
for (const e of enums) {
  const doc = [`${e.name} mirrors bettercompute.agent.v1.${e.name}.`, ...(e.doc.length ? ['', ...e.doc] : [])];
  types += `\n${docLines(doc)}type ${e.name} int32\n\n`;
  types += `// ${e.name} values.\nconst (\n`;
  types += aligned(e.values, '\t', (v) => [`${e.name}_${v.name}`, e.name, `= ${v.number}`]);
  types += ')\n';
}
for (const m of messages) {
  const doc = [`${m.name} mirrors bettercompute.agent.v1.${m.name}.`, ...(m.doc.length ? ['', ...m.doc] : [])];
  types += `\n${docLines(doc)}type ${m.name} struct {\n`;
  types += aligned(m.fields, '\t', (f) => [camel(f.name), goType(f)]);
  types += '}\n';
}

let encode = `${header}package inventory\n`;
for (const m of messages) {
  if (m.name === 'NodeInventory') continue; // never hashed as a whole
  encode += `\nfunc (m *${m.name}) encode(w *protoWriter) {\n\tif m == nil {\n\t\treturn\n\t}\n`;
  for (const f of m.fields) for (const l of encodeLine(f)) encode += `\t${l}\n`;
  encode += '}\n';
}

writeFileSync(join(here, 'types.go'), types);
writeFileSync(join(here, 'encode.go'), encode);
console.log(`types.go: ${enums.length} enums, ${messages.length} messages; encode.go: ${messages.length - 1} encoders`);
