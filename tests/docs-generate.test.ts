import { execFile } from 'node:child_process';
import { existsSync } from 'node:fs';
import { mkdtemp, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { promisify } from 'node:util';
import { describe, expect, it } from 'vitest';
// @ts-expect-error plain ESM script without types
import { checkDescriptions, firstParagraph, parseSections } from '../apps/docs/scripts/descriptions.mjs';

// The docs generator (apps/docs/scripts/generate.mjs) and what it writes. These checks need no build:
// they read the committed generated/*.json and pages. The full `generate.mjs --check` needs every
// package built (`tsc -b`) and runs with DOCS_GENERATE_CHECK=1.

const docs = join(import.meta.dirname, '..', 'apps', 'docs');
const run = promisify(execFile);
const readJson = async <T>(path: string): Promise<T> => JSON.parse(await readFile(join(docs, path), 'utf8')) as T;

interface ApiGroup {
  group: string;
  slug: string;
  module: string;
  methods: { method: string; status: 'registered' | 'planned'; summary: string }[];
}

describe('descriptions', () => {
  it('splits Markdown into ## sections, ignoring headings inside code fences', () => {
    const text = 'Overview.\r\n\r\nMore.\n\n## create\n\nMakes one.\n\nDetails.\n\n```md\n## not-a-heading\n```\n\n## list\n\nLists.';
    const sections = parseSections(text);
    expect([...sections.keys()]).toEqual(['', 'create', 'list']);
    expect(sections.get('')).toBe('Overview.\n\nMore.');
    expect(sections.get('create')).toContain('## not-a-heading');
    expect(firstParagraph(sections.get('create'))).toBe('Makes one.');
    expect(firstParagraph('  a\n  wrapped   line\n\nnext')).toBe('a wrapped line');
    expect(firstParagraph(undefined)).toBe('');
  });

  it('reports unknown groups, methods and error codes, and headings given twice', async () => {
    const dir = await mkdtemp(join(tmpdir(), 'bc-docs-'));
    try {
      await mkdir(join(dir, 'descriptions', 'api'), { recursive: true });
      await writeFile(join(dir, 'descriptions', 'api', 'nodes.md'), 'Nodes.\n\n## get\n\nOne.\n\n## gte\n\nTypo.\n\n## get\n\nAgain.');
      await writeFile(join(dir, 'descriptions', 'api', 'nopes.md'), 'x');
      await writeFile(join(dir, 'descriptions', 'api', 'notes.txt'), 'x');
      await writeFile(join(dir, 'descriptions', 'errors.md'), '## NOT_FOUND\n\nMissing.\n\n## NOPE\n\nx');
      const problems = await checkDescriptions(dir, {
        api: [{ group: 'nodes', slug: 'nodes', methods: [{ method: 'get' }, { method: 'list' }] }],
        errorCodes: ['NOT_FOUND'],
      });
      expect(problems).toEqual([
        'descriptions/api/nodes.md: ## get appears twice',
        'descriptions/api/nodes.md: ## gte is not a method of nodes',
        'descriptions/api/nopes.md: no API group nopes (groups are named as in generated/api.json)',
        'descriptions/api/notes.txt: only <group>.md files belong here',
        'descriptions/errors.md: ## NOPE is not an error code',
      ]);
    } finally {
      await rm(dir, { recursive: true, force: true });
    }
  });

  it('the committed descriptions name only real groups, methods and codes', async () => {
    const api = await readJson<ApiGroup[]>('generated/api.json');
    const errors = await readJson<{ code: string }[]>('generated/errors.json');
    expect(await checkDescriptions(docs, { api, errorCodes: errors.map((error) => error.code) })).toEqual([]);
  });
});

describe('generated reference', () => {
  it('has one page per API group, listed in the API meta.json in order', async () => {
    const api = await readJson<ApiGroup[]>('generated/api.json');
    expect(api.length).toBeGreaterThan(0);
    const meta = await readJson<{ pages: string[] }>('content/docs/reference/api/meta.json');
    expect(meta.pages).toEqual(['index', ...api.map((entry) => entry.slug)]);
    const pages = (await readdir(join(docs, 'content/docs/reference/api'))).filter((name) => name.endsWith('.mdx'));
    expect(pages.sort()).toEqual(['index', ...api.map((entry) => entry.slug)].map((slug) => `${slug}.mdx`).sort());
  });

  it('pages carry frontmatter and a section per method, and the generated marker', async () => {
    const api = await readJson<ApiGroup[]>('generated/api.json');
    for (const entry of api) {
      const page = (await readFile(join(docs, `content/docs/reference/api/${entry.slug}.mdx`), 'utf8')).replace(/\r\n/g, '\n');
      expect(page, entry.slug).toMatch(/^---\ntitle: .+\ndescription: .+\n---\n/);
      expect(page, entry.slug).toContain('Generated by apps/docs/scripts/generate.mjs');
      for (const method of entry.methods) expect(page, `${entry.slug}/${method.method}`).toContain(`\n## ${method.method}\n`);
    }
  });

  it('every other generated page exists with frontmatter', async () => {
    for (const name of ['cli', 'command-kinds', 'errors', 'events', 'metrics', 'modules', 'packages']) {
      const page = await readFile(join(docs, `content/docs/reference/${name}.mdx`), 'utf8');
      expect(page.replace(/\r\n/g, '\n'), name).toMatch(/^---\ntitle: .+\ndescription: .+\n---\n/);
    }
  });

  it('the metrics page lists every family of generated/metrics.json, prefixed and tenant-free', async () => {
    const metrics = await readJson<{ name: string; labels: string[] }[]>('generated/metrics.json');
    expect(metrics.length).toBeGreaterThan(20);
    const page = await readFile(join(docs, 'content/docs/reference/metrics.mdx'), 'utf8');
    for (const family of metrics) {
      expect(family.name, family.name).toMatch(/^better_compute_/);
      expect(family.labels, family.name).not.toContain('tenant');
      expect(page, family.name).toContain(`\`${family.name}\``);
    }
  });

  it('check-content finds no broken pages, links or meta entries', async () => {
    const { stdout } = await run(process.execPath, [join(docs, 'scripts', 'check-content.mjs')]);
    expect(stdout).toMatch(/no problems/);
  });

  const built = existsSync(join(import.meta.dirname, '..', 'packages', 'cli', 'dist', 'index.js'));
  it.runIf(process.env.DOCS_GENERATE_CHECK === '1' && built)(
    'generate.mjs --check: the committed reference matches the live registry',
    async () => {
      const { stdout } = await run(process.execPath, [join(docs, 'scripts', 'generate.mjs'), '--check'], {
        maxBuffer: 16 * 1024 * 1024,
      });
      expect(stdout).toMatch(/up to date/);
    },
    120_000,
  );
});
