// Vendors better-iam's packed tarballs and pins every @better-iam/* package to them.
//
//   node scripts/sync-better-iam.mjs            copy ../better-iam/artifacts/*.tgz (the default)
//   node scripts/sync-better-iam.mjs --pack     run `pnpm pack:all` inside better-iam first (only with the
//                                               user's approval: other sessions edit that tree, PLAN.md D13)
//   node scripts/sync-better-iam.mjs --install  also run `pnpm install --force` afterwards
//   node scripts/sync-better-iam.mjs --write    only regenerate pnpm-workspace.yaml from vendor/
//
// BETTER_IAM_DIR overrides the sibling checkout location.
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import { allowBuilds, root, runPnpm, workspacePackages } from './tooling.mjs';

const args = new Set(process.argv.slice(2));
const source = resolve(process.env.BETTER_IAM_DIR ?? join(root, '..', 'better-iam'));
const vendor = join(root, 'vendor', 'better-iam');

/** `better-iam-core-0.1.0.tgz` → `{ name: '@better-iam/core', version: '0.1.0' }`. */
function packageOf(file) {
  const match = /^(better-iam(?:-(.+?))?)-(\d+\.\d+\.\d+(?:-[\w.]+)?)\.tgz$/.exec(file);
  if (!match) throw new Error(`Unexpected tarball name: ${file}`);
  return { name: match[2] ? `@better-iam/${match[2]}` : 'better-iam', version: match[3] };
}

const sha256 = (path) => createHash('sha256').update(readFileSync(path)).digest('hex');

function copyArtifacts() {
  if (args.has('--pack')) {
    console.log(`Packing better-iam in ${source} (approved by the user per PLAN.md D13).`);
    const result = spawnSync(process.execPath, [join(source, 'scripts', 'pack.mjs')], {
      cwd: source,
      stdio: 'inherit',
    });
    if (result.status !== 0) throw new Error('better-iam pack failed');
  }
  const artifacts = join(source, 'artifacts');
  if (!existsSync(artifacts)) throw new Error(`No artifacts at ${artifacts}; run pack:all in better-iam first.`);
  const tarballs = readdirSync(artifacts).filter((file) => file.endsWith('.tgz'));
  if (tarballs.length === 0) throw new Error(`No tarballs in ${artifacts}.`);
  rmSync(vendor, { recursive: true, force: true });
  mkdirSync(vendor, { recursive: true });
  const files = {};
  let packedAt = 0;
  for (const file of tarballs.sort()) {
    copyFileSync(join(artifacts, file), join(vendor, file));
    files[file] = sha256(join(vendor, file));
    packedAt = Math.max(packedAt, statSync(join(artifacts, file)).mtimeMs);
  }
  const versions = new Set(tarballs.map((file) => packageOf(file).version));
  writeFileSync(
    join(vendor, 'SOURCE.json'),
    JSON.stringify(
      {
        source,
        packedAt: new Date(packedAt).toISOString(),
        copiedAt: new Date().toISOString(),
        versions: [...versions],
        files,
      },
      null,
      2,
    ) + '\n',
  );
  console.log(`Vendored ${tarballs.length} better-iam tarballs into vendor/better-iam.`);
}

function writeWorkspace() {
  const tarballs = readdirSync(vendor).filter((file) => file.endsWith('.tgz')).sort();
  const quote = (value) => (/^[\w.-]+$/.test(value) ? value : `'${value}'`);
  const lines = [
    '# Generated by scripts/sync-better-iam.mjs from scripts/tooling.mjs and vendor/better-iam; do not edit by hand.',
    'packages:',
    ...workspacePackages.map((glob) => `  - ${glob}`),
    '',
    'allowBuilds:',
    ...Object.entries(allowBuilds).map(([name, allowed]) => `  ${quote(name)}: ${allowed}`),
    '',
    '# Several sessions share this tree: `pnpm exec`/`pnpm run` must never start an install on their own.',
    'verifyDepsBeforeRun: false',
    '',
    '# better-iam is not published yet: every package, including transitive ones, resolves to a vendored tarball.',
    'overrides:',
    ...tarballs.map((file) => `  ${quote(packageOf(file).name)}: file:vendor/better-iam/${file}`),
    '',
  ];
  writeFileSync(join(root, 'pnpm-workspace.yaml'), lines.join('\n'));
  console.log(`Wrote pnpm-workspace.yaml with ${tarballs.length} overrides.`);
}

if (!args.has('--write')) copyArtifacts();
writeWorkspace();
if (args.has('--install')) runPnpm(['install', '--force'], { cwd: root });
