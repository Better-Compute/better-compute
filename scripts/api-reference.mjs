// Writes docs/api-reference.md from the server's method registry and PLAN.md §9.2 (core's
// `apiSurface`), marking each method registered (routed by this build) or planned.
//
//   node scripts/api-reference.mjs           (pnpm docs:api)
//   node scripts/api-reference.mjs --check   fails when docs/api-reference.md is out of date
//
// Reads the built packages: run `tsc -b packages/server packages/postgres` first. The server is
// built on a PGlite executor and a refusing IamPort; generating the page opens neither.
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import prettier from 'prettier';
import { root } from './tooling.mjs';

const check = process.argv.includes('--check');
const output = join(root, 'docs', 'api-reference.md');
const built = {
  core: join(root, 'packages', 'core', 'dist', 'index.js'),
  server: join(root, 'packages', 'server', 'dist', 'index.js'),
  pglite: join(root, 'packages', 'postgres', 'dist', 'pglite.js'),
};
for (const path of Object.values(built))
  if (!existsSync(path)) {
    console.error(`${path} is missing; run: pnpm exec tsc -b packages/server packages/postgres`);
    process.exit(1);
  }
const load = (path) => import(pathToFileURL(path).href);
const { apiSurface, defaultStatus, errorCodes } = await load(built.core);
const { betterCompute, maxBodyBytes, serverVersion } = await load(built.server);
const { pglite } = await load(built.pglite);

const refuse = () => Promise.reject(new Error('api-reference never calls IAM'));
const database = pglite();
const compute = betterCompute({
  database,
  iam: {
    authenticate: refuse,
    require: refuse,
    authorize: refuse,
    authorizeMany: refuse,
    requestConfirmation: refuse,
    billingCheck: refuse,
    recordUsage: refuse,
    featureEnabled: refuse,
    capabilities: () => ({
      pluginResolver: false,
      eventDetail: false,
      evaluate: false,
      readOnlyDecisions: false,
    }),
  },
  secret: 'api-reference-placeholder-secret-0123456789',
  baseURL: 'http://localhost',
  rootTenantId: 'root',
});
const { registry, endpoint } = compute;

const code = (text) => `\`${text}\``;
const authorization = (row) => {
  if (row.action === null) return 'public';
  const pairs = [{ action: row.action, resource: row.resource }, ...(row.alternatives ?? [])];
  const text = pairs
    .map(({ action, resource }) => `${code(action)} @ ${code(`compute-${resource}`)}`)
    .join(' or ');
  return row.list ? `${text} + items` : text;
};

const lines = [
  '# API reference',
  '',
  '<!-- Generated by scripts/api-reference.mjs (pnpm docs:api) from the method registry of @better-compute/server and PLAN.md §9.2. Do not edit by hand. -->',
  '',
  `@better-compute/server ${serverVersion} serves ${code(`POST ${endpoint.basePath}/{group}/{method}`)}.`,
  '',
  '## Calling the API',
  '',
  `- ${code('POST {basePath}/{group}/{method}')}, and ${code('POST {basePath}/plugins/{id}/{group}/{method}')} for plugins. The default base path is ${code(endpoint.basePath)}.`,
  `- Requests need ${code('content-type: application/json')} and ${code('X-Better-Compute: 1')}, or they are refused with ${code('CSRF_REJECTED')}. The body is a JSON object of at most ${maxBodyBytes / 1024} KiB.`,
  `- Credentials: an IAM bearer token, or a session JWT whose audience includes compute. The IAM session cookie counts only when the server sets ${code('acceptIamCookie')}, and then only from the server's exact origin.`,
  `- Answers: ${code('{ "data": … }')}, or ${code('{ "error": { "code", "message", "retryAfterMs"?, "details"? } }')} with the status below. A valid ${code('X-Request-Id')} is echoed; otherwise the server assigns one.`,
  `- The only GET routes are ${code('{basePath}/health')} and ${code('{basePath}/.well-known/better-compute')}.`,
  `- Typed client: ${code('createComputeClient<typeof compute>({ baseURL, token })')} from ${code('@better-compute/client')}.`,
  '',
  '## Methods',
  '',
  'Every call is authenticated (except public methods), refused before any database access when the caller is outside the input tenant and the root tenant, and decided once on `action @ resource`. *+ items* marks the list recipe. **Registered** methods are routed by this build; a registered stub answers `NOT_IMPLEMENTED` naming its phase. **Planned** methods arrive in the phase shown.',
];
const groups = [...new Set(apiSurface.map((row) => row.group))];
for (const group of groups) {
  const rows = apiSurface.filter((row) => row.group === group);
  lines.push('', `### ${code(group)} (${rows[0].module})`, '');
  lines.push(
    '| Method | Kind | Authorization | Phase | Status |',
    '| --- | --- | --- | --- | --- |',
  );
  for (const row of rows) {
    const status = registry.method(`${row.group}/${row.method}`) ? 'registered' : 'planned';
    lines.push(
      `| ${code(`${row.group}.${row.method}`)} | ${row.kind} | ${authorization(row)} | ${row.phase} | ${status} |`,
    );
  }
}
const extra = registry.methods.filter((method) => !method.row);
if (extra.length) {
  lines.push('', '### Plugin and other methods', '');
  lines.push('| Route | Kind | Action | Module |', '| --- | --- | --- | --- |');
  for (const method of extra)
    lines.push(
      `| ${code(method.path)} | ${method.kind} | ${method.action ? code(method.action) : 'public'} | ${method.module} |`,
    );
}
lines.push('', '## Errors', '', '| Code | HTTP status |', '| --- | --- |');
for (const errorCode of errorCodes)
  lines.push(`| ${code(errorCode)} | ${defaultStatus[errorCode]} |`);

const config = (await prettier.resolveConfig(output)) ?? {};
const page = await prettier.format(`${lines.join('\n')}\n`, { ...config, parser: 'markdown' });
await database.close();

if (check) {
  const current = existsSync(output) ? await readFile(output, 'utf8') : '';
  if (current.replace(/\r\n/g, '\n') !== page) {
    console.error('docs/api-reference.md is out of date; run: pnpm docs:api');
    process.exitCode = 1;
  } else console.log('docs/api-reference.md is up to date.');
} else {
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, page);
  console.log(
    `Wrote docs/api-reference.md (${apiSurface.length} methods, ${registry.methods.length} registered).`,
  );
}
